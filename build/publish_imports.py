#!/usr/bin/env python3
"""Publish the converted Trello imports into the Notion wiki.

  python build/publish_imports.py            # publish everything not yet published
  python build/publish_imports.py --dry-run  # list what would be created
  python build/publish_imports.py --only pip # substring of a converted file's path

Reads imports/MANIFEST.json for each card's group and target, and the matching
file under imports/converted/<group>/<slug>.md. Characters go as a page under
their target volume's Character Cards page (Volume VI is created here the
first time it is needed). Everything else goes under a new top-level wiki
row, The Iridescent Archive, with four sub-pages: Techniques, Spellcraft,
Artifacts, Bestiary Additions -- also created here the first time.

After publishing, runs build/notion_export.py so wiki/ mirrors the new pages
with the right section (the exporter walks the live Notion tree, so it gets
this right regardless of what this script's own bookkeeping thinks).

Idempotent: build/.publish_imports.json remembers the container page ids and,
per converted file, the page it made. Re-running only publishes files not yet
in that map.

Refuses to publish a converted file that still reads like an unresolved draft
(a "pending Isaac" / "TBD" placeholder, or a standing-restriction
flag stub) -- run the resolve pass on it first. Held files are listed at the
end and written to reports/publish_imports_held.md.

Needs NOTION_TOKEN.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "build"))
from notion_export import DATABASE_ID, api  # noqa: E402
from notion_publish import BATCH, create_page, md_to_blocks  # noqa: E402

MAP = ROOT / "build" / ".publish_imports.json"
MANIFEST = ROOT / "imports" / "MANIFEST.json"
CONVERTED = ROOT / "imports" / "converted"

CHAR_VOLUME_IDS = {
    "Volume IV — Character Cards": "3bd58200-eb22-81a1-bcab-cb47f888ca98",
    "Volume V — Character Cards": "3bd58200-eb22-81d5-a85a-f46b3422fdb5",
}
ARCHIVE_SECTIONS = ["Techniques", "Spellcraft", "Artifacts", "Bestiary Additions"]
ARCHIVE_TARGET_RE = re.compile(r"^The Iridescent Archive / (.+)$")

HOLD_RE = re.compile(r"pending Isaac|\bTBD\b|STANDING RESTRICTION", re.I)

# Manually reviewed: HOLD_RE matches these on prose that explains a slot was
# CLOSED ("... in place of the card's TBD", "STANDING RESTRICTION, resolved:
# the card stands, built") or cites another card's still-open flag without
# reopening it here -- not a real placeholder in this file. Checked by hand
# 2026-09-12 before adding.
HOLD_FALSE_POSITIVES = {
    "imports/converted/characters/deserts_fang.md",
    "imports/converted/characters/he_who_bears_the_will_of_the_titans.md",
    "imports/converted/characters/the_forge_that_roars.md",
    "imports/converted/characters/volume_vi_the_fractured_dawn_paragons_of_the_archons.md",
}


def create_row(title: str, tags: list, blocks: list) -> str:
    body = {
        "parent": {"database_id": DATABASE_ID},
        "properties": {
            "title": {"title": [{"type": "text", "text": {"content": title[:2000]}}]},
            "Tags": {"multi_select": [{"name": t} for t in tags]},
        },
        "children": blocks[:BATCH],
    }
    page = api("POST", "/pages", body)
    for i in range(BATCH, len(blocks), BATCH):
        api("PATCH", f"/blocks/{page['id']}/children", {"children": blocks[i:i + BATCH]})
    return page["id"]


def ensure_volume_vi(m: dict) -> str:
    if m.get("_volume_vi"):
        return m["_volume_vi"]
    blocks = md_to_blocks(
        "Character cards migrated from the old Trello board and converted onto the "
        "current Fracture of Worlds system. Generated by build/publish_imports.py; "
        "edit the repo, not this page."
    )
    pid = create_row("Volume VI — Character Cards", ["Characters"], blocks)
    m["_volume_vi"] = pid
    MAP.write_text(json.dumps(m, indent=2, ensure_ascii=False), encoding="utf-8")
    return pid


def ensure_archive(m: dict) -> dict:
    if m.get("_archive_sections"):
        return m["_archive_sections"]
    intro = md_to_blocks(
        "Techniques, Spellcraft, Artifacts and Bestiary entries migrated from the old "
        "Trello board and converted onto the current Fracture of Worlds system. Not "
        "character sheets -- those are under Characters. Generated by "
        "build/publish_imports.py; edit the repo, not this page.\n\n"
        "- Techniques\n- Spellcraft\n- Artifacts\n- Bestiary Additions"
    )
    create_row("The Iridescent Archive", ["The Iridescent Archive"], intro)
    sections = {}
    for name in ARCHIVE_SECTIONS:
        sections[name] = create_row(name, ["The Iridescent Archive"], md_to_blocks(
            f"{name} migrated from the old Trello board. See build/publish_imports.py."))
    m["_archive_sections"] = sections
    MAP.write_text(json.dumps(m, indent=2, ensure_ascii=False), encoding="utf-8")
    return sections


def container_for(target: str, m: dict) -> str:
    if target in CHAR_VOLUME_IDS:
        return CHAR_VOLUME_IDS[target]
    if target == "Volume VI — Character Cards":
        return ensure_volume_vi(m)
    am = ARCHIVE_TARGET_RE.match(target)
    if am:
        return ensure_archive(m)[am.group(1)]
    raise ValueError(f"unknown target: {target}")


def item_title(md: str, fallback: str) -> str:
    m = re.search(r"(?m)^#\s+(.+?)\s*$", md)
    return m.group(1).strip().strip("*") if m else fallback


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--only", help="substring of a converted file's path")
    ap.add_argument("--skip-export", action="store_true", help="do not run notion_export.py at the end")
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    m = json.loads(MAP.read_text(encoding="utf-8")) if MAP.exists() else {}

    todo, held, missing = [], [], []
    for entry in manifest:
        group, target = entry["group"], entry["target"]
        slug = Path(entry["file"]).stem
        rel = f"imports/converted/{group}/{slug}.md"
        path = ROOT / rel
        if args.only and args.only.lower() not in rel.lower():
            continue
        if not path.exists():
            missing.append(rel)
            continue
        if m.get(rel):
            continue
        md = path.read_text(encoding="utf-8", errors="replace")
        if HOLD_RE.search(md) and rel not in HOLD_FALSE_POSITIVES:
            held.append(rel)
            continue
        todo.append((rel, group, target, slug, md))

    print(f"{len(manifest)} in manifest, {len(missing)} not yet converted, "
          f"{len(held)} held (unresolved/flagged), {len(todo)} to publish")
    if held:
        report = ROOT / "reports" / "publish_imports_held.md"
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(
            "# Held out of the Notion publish\n\n"
            "Contains a \"pending Isaac\" / TBD placeholder, or is a "
            "standing-restriction flag stub. Run the resolve pass, or get Isaac's "
            "ruling, then re-run build/publish_imports.py.\n\n"
            + "\n".join(f"- {r}" for r in sorted(held)) + "\n",
            encoding="utf-8",
        )
        print(f"  held list written to {report.relative_to(ROOT)}")

    if args.dry_run:
        for rel, group, target, slug, md in todo:
            print(f"  create  {rel}  ->  {target}  ({item_title(md, slug)})")
        return 0

    for n, (rel, group, target, slug, md) in enumerate(todo, 1):
        parent_id = container_for(target, m)
        title = item_title(md, slug)
        pid = create_page({"page_id": parent_id}, title, md_to_blocks(md))
        m[rel] = {"page_id": pid, "title": title, "target": target}
        MAP.write_text(json.dumps(m, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"  [{n}/{len(todo)}] created {rel} -> {target} :: {title}")

    if todo and not args.skip_export:
        print("re-exporting the wiki so wiki/ mirrors the new pages...")
        subprocess.run([sys.executable, str(ROOT / "build" / "notion_export.py")], check=False)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())

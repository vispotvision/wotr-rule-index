"""Rewrite wiki/INDEX.md: every page in the vault, by section and shelf, as wikilinks.

  python build/wiki_index.py
"""
import json, re
from pathlib import Path

WIKI = Path(__file__).resolve().parent.parent / "wiki"
SKIP = {"INDEX.md"}


def title(p: Path) -> str:
    m = re.search(r'(?m)^title:\s*"?(.*?)"?\s*$', p.read_text(encoding="utf-8")[:1500])
    return m.group(1).replace('\\"', '"') if m else p.stem


def main() -> None:
    man = json.loads((WIKI / ".manifest.json").read_text(encoding="utf-8")).values()
    private = {m["rel"] for m in man if m.get("private")}
    pages = sorted(p for p in WIKI.rglob("*.md") if not any(x.startswith(".") for x in p.relative_to(WIKI).parts)
                   and p.name not in SKIP and p.relative_to(WIKI).parts[0] != "Assets")
    out = ["# War of the Realms — every page in the vault", "",
           f"{len(pages)} pages. The wiki is this vault (Notion is retired); public pages publish to "
           "https://vispotvision.github.io/wotr-rule-index/. Regenerated by `build/wiki_index.py` on each autosave.", ""]
    root = [p for p in pages if len(p.relative_to(WIKI).parts) == 1]
    out += ["## The front door", ""] + [f"- [[{p.relative_to(WIKI).as_posix()[:-3]}|{title(p)}]]" for p in root] + [""]
    seen = set()
    for p in pages:
        parts = p.relative_to(WIKI).parts
        if len(parts) == 1:
            continue
        folders = parts[:-1]
        for depth in range(1, len(folders) + 1):
            key = folders[:depth]
            if key not in seen:
                seen.add(key)
                out += ["", "#" * min(depth + 1, 6) + " " + key[-1], ""]
        rel = p.relative_to(WIKI).as_posix()
        lock = " · private" if rel in private else ""
        out.append(f"- [[{rel[:-3]}|{title(p)}]]{lock}")
    (WIKI / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(pages)} pages -> wiki/INDEX.md")


if __name__ == "__main__":
    main()
